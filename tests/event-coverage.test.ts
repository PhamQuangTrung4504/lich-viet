const MONTH_REVIEW = {
  solar: [
    'covered', 'covered', 'covered', 'covered', 'covered', 'covered',
    'covered', 'covered', 'covered', 'covered', 'covered', 'covered',
  ],
  lunar: [
    'covered', 'no_approved_candidate', 'covered', 'covered', 'covered', 'no_approved_candidate',
    'covered', 'covered', 'covered', 'covered', 'no_approved_candidate', 'covered',
  ],
} as const

function actualRule(event: (typeof VERIFIED_EVENTS)[number]): string {
  const rule = event.rule
  switch (rule.type) {
    case 'solar_fixed': return `solar:${rule.month}:${rule.day}${rule.startYear === undefined ? '' : `:start=${rule.startYear}`}`
    case 'lunar_fixed': return `lunar:${rule.month}:${rule.day}:${rule.leapMonthPolicy}`
    case 'lunar_month_end': return `lunar_month_end:${rule.month}`
    case 'weekday_rule': return `weekday_rule:${rule.month}:${rule.weekday}:${rule.occurrence}`
    case 'year_specific': return `year_specific:${rule.date.year}-${rule.date.month}-${rule.date.day}`
  }
}

test('coverage inventory accounts for every production event and its date/classification contract', () => {
  const candidateIds = CANDIDATES.map(({ id }) => id)
  const productionIds = VERIFIED_EVENTS.map(({ id }) => id)
  assert.equal(new Set(candidateIds).size, candidateIds.length, 'candidate IDs must be unique')
  assert.equal(new Set(productionIds).size, productionIds.length, 'production IDs must be unique')

  const candidatesById = new Map(CANDIDATES.map((candidate) => [candidate.id, candidate]))
  for (const event of VERIFIED_EVENTS) {
    const candidate = candidatesById.get(event.id)
    assert.ok(candidate, `${event.id} is missing from the independent candidate inventory`)
    assert.equal(candidate.status, 'approved', `${event.id} is not approved for production`)
    assert.equal(event.title, candidate.title, `${event.id} title/alias review differs`)
    assert.equal(event.category, candidate.category, `${event.id} holiday classification differs`)
    assert.equal(actualRule(event), candidate.expectedRule, `${event.id} recurrence/effective-date rule differs`)
    assert.ok(event.sources.length > 0, `${event.id} needs a source to be considered approved`)
  }
  assert.equal(CANDIDATES.filter(({ status }) => status === 'approved').length, productionIds.length)
  for (const candidate of CANDIDATES.filter(({ status }) => status !== 'approved')) {
    assert.ok(candidate.reviewNote?.trim(), `${candidate.id} needs a reason for its non-production status`)
    assert.ok(!productionIds.includes(candidate.id), `${candidate.id} is not approved and must not enter production`)
  }
})

test('candidate aliases do not silently identify two distinct occasions', () => {
  const aliases = new Map<string, string>()
  for (const candidate of CANDIDATES) {
    for (const alias of [candidate.title, ...(candidate.aliases ?? [])]) {
      const normalized = alias.normalize('NFC').toLocaleLowerCase('vi').replace(/[()]/g, '').trim()
      const previous = aliases.get(normalized)
      assert.ok(previous === undefined || previous === candidate.id, `Alias "${alias}" collides between ${previous} and ${candidate.id}`)
      aliases.set(normalized, candidate.id)
    }
  }
  assert.notEqual(candidatesById('trung-thap').expectedRule, candidatesById('ha-nguyen').expectedRule)
})

function candidatesById(id: string): Candidate {
  const candidate = CANDIDATES.find((entry) => entry.id === id)
  assert.ok(candidate, `Missing candidate ${id}`)
  return candidate
}

test('12-month solar/lunar inventory explicitly records reviewed gaps instead of implying completeness', () => {
  for (const calendar of ['solar', 'lunar'] as const) {
    assert.equal(MONTH_REVIEW[calendar].length, 12)
    for (const [index, status] of MONTH_REVIEW[calendar].entries()) {
      assert.ok(status === 'covered' || status === 'no_approved_candidate', `${calendar} month ${index + 1} needs a review status`)
    }
    const coveredMonths = new Set(CANDIDATES
      .filter(({ status }) => status === 'approved')
      .flatMap(({ expectedRule }) => {
        const ruleType = expectedRule.split(':')[0]
        if (calendar === 'solar' && ruleType !== 'solar') return []
        if (calendar === 'lunar' && ruleType !== 'lunar' && ruleType !== 'lunar_month_end') return []
        return [Number(expectedRule.split(':')[1])]
      }))
    for (const [index, status] of MONTH_REVIEW[calendar].entries()) {
      assert.equal(status === 'covered', coveredMonths.has(index + 1), `${calendar} month ${index + 1} inventory status is inconsistent`)
    }
  }
  assert.deepEqual(MONTH_REVIEW.lunar.flatMap((status, index) => status === 'no_approved_candidate' ? [index + 1] : []), [2, 6, 11])
})

test('independent Thất Tịch references map 7/7 lunar to 10 August 2024 and 19 August 2026', () => {
  // VTV/TTXVN reports 10/08/2024 as Thất Tịch: https://vtv.vn/doi-song/hom-nay-ngay-that-tich-vi-sao-nen-an-che-dau-do-20240810134039121.htm
  // amlichchuan reports 19/08/2026 as lunar 7/7: https://amlichchuan.com/lich-am/2026-08-19
  for (const solar of [createCivilDate(2024, 8, 10), createCivilDate(2026, 8, 19)]) {
    assert.deepEqual(solarToVietnameseLunar(solar), {
      year: solar.year, month: 7, day: 7, isLeapMonth: false,
    })
    const matches = findEventsForDate(solar)
    assert.ok(matches.some(({ id }) => id === 'that-tich'))
    const event = matches.find(({ id }) => id === 'that-tich')
    assert.ok(event?.rule.type === 'lunar_fixed')
    assert.equal(event.rule.leapMonthPolicy, 'regular_only')
    assert.deepEqual(event.sources.map(({ url }) => url), [
      'https://vov.vn/doi-song/that-tich-2026-la-ngay-nao-thu-may-post1324704.vov',
      'https://vtv.vn/doi-song/nguon-goc-va-y-nghia-cua-le-that-tich-2021081414364009.htm',
      'https://dulieu.itrithuc.vn/media/dataset/2020_08/ky_05778.pdf',
    ])
  }
  assert.ok(!findEventsForDate(createCivilDate(2024, 8, 10)).some(({ id }) => id === 'ha-nguyen'))
})

test('the two names and dates in lunar month ten remain distinct', () => {
  assert.deepEqual(findEventsForDate(createCivilDate(2026, 11, 18)).filter(({ id }) => id === 'trung-thap').map(({ title }) => title), ['Tết Trùng Thập'])
  assert.deepEqual(findEventsForDate(createCivilDate(2026, 11, 23)).filter(({ id }) => id === 'ha-nguyen').map(({ title }) => title), ['Tết Hạ Nguyên (Rằm tháng Mười)'])
})
